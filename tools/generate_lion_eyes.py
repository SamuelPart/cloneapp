#!/usr/bin/env python3
"""Regenerate the 12 eye overlays used by the SamPlay welcome animation.

The vector resources need only the Python standard library. For a visual preview,
install Pillow separately and pass --preview /path/to/preview.gif. The preview
loops for review; the app plays the sequence once and then opens the content.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAWABLE = ROOT / "app/src/main/res/drawable"
BASE_IMAGE = ROOT / "app/src/main/res/drawable-nodpi/samplay_lion_animation_base.png"
FONT = ROOT / "app/src/main/res/font/inter_black.ttf"
EYE_COLOR = "#FF0A0A0A"


def line(x1, y1, x2, y2, width=8):
    return ("line", x1, y1, x2, y2, width)


def curve(x1, y1, cx, cy, x2, y2, width=8):
    return ("curve", x1, y1, cx, cy, x2, y2, width)


def rect(x, y, width, height, radius=4):
    return ("rect", x, y, width, height, radius)


def polygon(*points):
    return ("polygon", *points)


def circle(x, y, radius):
    return ("circle", x, y, radius)


# Row-major order matches the user's 4-row, 3-column expression reference.
