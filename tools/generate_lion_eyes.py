def rounded_rect_path(x, y, width, height, radius):
    right, bottom = x + width, y + height
    return (
        f"M{x+radius},{y} L{right-radius},{y} Q{right},{y} {right},{y+radius} "
        f"L{right},{bottom-radius} Q{right},{bottom} {right-radius},{bottom} "
        f"L{x+radius},{bottom} Q{x},{bottom} {x},{bottom-radius} "
        f"L{x},{y+radius} Q{x},{y} {x+radius},{y} Z"
    )


def vector_path(mark):
    kind, *args = mark
    if kind == "line":
        x1, y1, x2, y2, width = args
        return f"M{x1},{y1} L{x2},{y2}", width
    if kind == "curve":
        x1, y1, cx, cy, x2, y2, width = args
        return f"M{x1},{y1} Q{cx},{cy} {x2},{y2}", width
    if kind == "rect":
        return rounded_rect_path(*args), None
    if kind == "polygon":
        return "M" + " L".join(f"{x},{y}" for x, y in args) + " Z", None
    if kind == "circle":
        x, y, radius = args
        return (f"M{x-radius},{y} A{radius},{radius} 0 1,0 {x+radius},{y} "
                f"A{radius},{radius} 0 1,0 {x-radius},{y} Z"), None
    raise ValueError(f"Unknown mark: {kind}")


def write_vectors():
    DRAWABLE.mkdir(parents=True, exist_ok=True)
    for index, (name, marks) in enumerate(FRAMES, 1):
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            f'<!-- Expression {index}: {name}. Generated by tools/generate_lion_eyes.py. -->',
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    android:width="512dp"',
            '    android:height="512dp"',
            '    android:viewportWidth="512"',
            '    android:viewportHeight="512">',
        ]
        for mark in marks:
            path, width = vector_path(mark)
            if width is None:
                lines += ['    <path', f'        android:fillColor="{EYE_COLOR}"',
                          f'        android:pathData="{path}" />']
            else:
                lines += ['    <path', '        android:fillColor="#00000000"',
                          f'        android:strokeColor="{EYE_COLOR}"',
                          f'        android:strokeWidth="{width}"',
                          '        android:strokeLineCap="round"',
                          '        android:strokeLineJoin="round"',
                          f'        android:pathData="{path}" />']
        lines += ['</vector>', '']
        (DRAWABLE / f"samplay_lion_eyes_{index:02}.xml").write_text("\n".join(lines), encoding="utf-8")


def draw_preview_mark(draw, mark, scale):
    kind, *args = mark
    fill = (10, 10, 10, 255)

    def point(x, y):
        return (round(x * scale), round(y * scale))

    if kind == "line":
        x1, y1, x2, y2, width = args
        points = [point(x1, y1), point(x2, y2)]
    elif kind == "curve":
        x1, y1, cx, cy, x2, y2, width = args
        points = []
        for step in range(25):
            t = step / 24
            x = (1-t)**2*x1 + 2*(1-t)*t*cx + t*t*x2
            y = (1-t)**2*y1 + 2*(1-t)*t*cy + t*t*y2
            points.append(point(x, y))
    elif kind == "rect":
        x, y, width, height, radius = args
        draw.rounded_rectangle((*point(x, y), *point(x+width, y+height)), radius=round(radius*scale), fill=fill)
        return
    elif kind == "circle":
        x, y, radius = args
        draw.ellipse((*point(x-radius, y-radius), *point(x+radius, y+radius)), fill=fill)
        return
    elif kind == "polygon":
        draw.polygon([point(x, y) for x, y in args], fill=fill)
        return
    else:
        raise ValueError(kind)

    thickness = max(1, round(width * scale))
    draw.line(points, fill=fill, width=thickness, joint="curve")
    radius = thickness / 2
    for x, y in (points[0], points[-1]):
        draw.ellipse((math.floor(x-radius), math.floor(y-radius), math.ceil(x+radius), math.ceil(y+radius)), fill=fill)


def write_preview(path: Path):
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError as exc:
        raise SystemExit("Pillow is required only for --preview") from exc

    # A phone-shaped visual reference; the app lays out the same artwork responsively.
    canvas_width, canvas_height, lion_size = 720, 1000, 530
    base = Image.open(BASE_IMAGE).convert("RGBA").resize((lion_size, lion_size), Image.Resampling.LANCZOS)
    font = ImageFont.truetype(str(FONT), 52)
    images = []
    for _, marks in FRAMES:
        image = Image.new("RGBA", (canvas_width, canvas_height), (0, 0, 0, 255))
        lion = base.copy()
        draw = ImageDraw.Draw(lion)
        for mark in marks:
            draw_preview_mark(draw, mark, lion_size / 512)
        image.alpha_composite(lion, ((canvas_width-lion_size)//2, 155))
        draw = ImageDraw.Draw(image)
        word_width = draw.textlength("Sam", font=font) + draw.textlength("Play", font=font)
        start_x = (canvas_width-word_width) / 2
        draw.text((start_x, 716), "Sam", font=font, fill="white")
        draw.text((start_x + draw.textlength("Sam", font=font), 716), "Play", font=font, fill=(84, 195, 242))
        images.append(image.convert("RGB").quantize(colors=192, method=Image.Quantize.MEDIANCUT))
    path.parent.mkdir(parents=True, exist_ok=True)
    images[0].save(path, save_all=True, append_images=images[1:], duration=1000, loop=0, disposal=2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", type=Path, help="write a looping GIF preview (requires Pillow)")
    args = parser.parse_args()
    write_vectors()
    if args.preview:
        write_preview(args.preview)


if __name__ == "__main__":
    main()
